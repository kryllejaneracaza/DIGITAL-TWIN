BEGIN TRANSACTION;
CREATE TABLE IF NOT EXISTS "Appliance_States" (
	"states_ID"	INTEGER,
	"appliances_ID"	INTEGER NOT NULL UNIQUE,
	"reported_state"	TEXT DEFAULT 'off',
	"desired_state"	TEXT DEFAULT 'off',
	"in_sync"	INTEGER DEFAULT 1,
	"updated_at"	TEXT DEFAULT (datetime('now')),
	PRIMARY KEY("states_ID" AUTOINCREMENT),
	FOREIGN KEY("appliances_ID") REFERENCES "Appliances"("appliances_ID") ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS "Appliances" (
	"appliances_ID"	INTEGER,
	"room_ID"	INTEGER NOT NULL,
	"controllers_ID"	INTEGER,
	"appliances_name"	TEXT NOT NULL,
	"appliances_type"	TEXT,
	"gpio_pin"	INTEGER,
	"pos_x"	REAL,
	"pos_y"	REAL,
	PRIMARY KEY("appliances_ID" AUTOINCREMENT),
	FOREIGN KEY("controllers_ID") REFERENCES "Controllers"("controllers_ID") ON DELETE SET NULL,
	FOREIGN KEY("room_ID") REFERENCES "Room"("room_ID") ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS "Automation_Rules" (
	"rules_ID"	INTEGER,
	"room_ID"	INTEGER NOT NULL,
	"appliances_ID"	INTEGER NOT NULL,
	"rule_name"	TEXT,
	"trigger_type"	TEXT NOT NULL,
	"threshold"	REAL,
	"duration_minutes"	INTEGER,
	"action"	TEXT NOT NULL,
	"target_value"	REAL,
	"is_active"	INTEGER NOT NULL DEFAULT 1,
	"created_at"	TEXT DEFAULT (datetime('now')),
	PRIMARY KEY("rules_ID" AUTOINCREMENT),
	FOREIGN KEY("appliances_ID") REFERENCES "Appliances"("appliances_ID") ON DELETE CASCADE,
	FOREIGN KEY("room_ID") REFERENCES "Room"("room_ID") ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS "Building" (
	"building_ID"	INTEGER,
	"building_name"	TEXT NOT NULL,
	"location"	TEXT,
	PRIMARY KEY("building_ID" AUTOINCREMENT)
);
CREATE TABLE IF NOT EXISTS "Commands" (
	"command_ID"	INTEGER,
	"appliances_ID"	INTEGER NOT NULL,
	"user_ID"	INTEGER,
	"rule_ID"	INTEGER,
	"source"	TEXT,
	"action"	TEXT NOT NULL,
	"status"	TEXT NOT NULL DEFAULT 'pending',
	"sent_at"	TEXT,
	"confirmed_at"	TEXT,
	"response_ms"	INTEGER,
	"created_at"	TEXT NOT NULL DEFAULT (datetime('now')),
	PRIMARY KEY("command_ID" AUTOINCREMENT),
	FOREIGN KEY("appliances_ID") REFERENCES "Appliances"("appliances_ID") ON DELETE CASCADE,
	FOREIGN KEY("rule_ID") REFERENCES "Automation_Rules"("rules_ID") ON DELETE SET NULL,
	FOREIGN KEY("user_ID") REFERENCES "Users"("users_ID") ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS "Controllers" (
	"controllers_ID"	INTEGER,
	"room_ID"	INTEGER NOT NULL,
	"controllers_name"	TEXT NOT NULL,
	"mac_address"	TEXT UNIQUE,
	"ip_address"	TEXT,
	"status"	TEXT DEFAULT 'offline',
	"wifi"	INTEGER,
	"last_seen"	TEXT,
	PRIMARY KEY("controllers_ID" AUTOINCREMENT),
	FOREIGN KEY("room_ID") REFERENCES "Room"("room_ID") ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS "Detection" (
	"detection_ID"	INTEGER,
	"reading_ID"	INTEGER,
	"room_ID"	INTEGER NOT NULL,
	"detection_type"	TEXT,
	"detection_result"	TEXT,
	"detected_at"	TEXT NOT NULL DEFAULT (datetime('now')),
	PRIMARY KEY("detection_ID" AUTOINCREMENT),
	FOREIGN KEY("reading_ID") REFERENCES "Sensor_Readings"("readings_ID") ON DELETE SET NULL,
	FOREIGN KEY("room_ID") REFERENCES "Room"("room_ID") ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS "IR_Command_Codes" (
	"code_ID"	INTEGER,
	"appliances_ID"	INTEGER NOT NULL,
	"action"	TEXT NOT NULL,
	"protocol"	TEXT,
	"raw_code"	TEXT,
	PRIMARY KEY("code_ID" AUTOINCREMENT),
	FOREIGN KEY("appliances_ID") REFERENCES "Appliances"("appliances_ID") ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS "Login_History" (
	"login_history_ID"	INTEGER,
	"user_ID"	INTEGER,
	"login_time"	TEXT DEFAULT (datetime('now')),
	"login_status"	TEXT,
	"raw_code"	TEXT,
	PRIMARY KEY("login_history_ID" AUTOINCREMENT),
	FOREIGN KEY("user_ID") REFERENCES "Users"("users_ID") ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS "Notifications" (
	"notification_ID"	INTEGER,
	"user_ID"	INTEGER,
	"room_ID"	INTEGER,
	"detection_ID"	INTEGER,
	"command_ID"	INTEGER,
	"notification_message"	TEXT NOT NULL,
	"notification_is_read"	INTEGER NOT NULL DEFAULT 0,
	"notification_sent_at"	TEXT NOT NULL DEFAULT (datetime('now')),
	"delivered_at"	TEXT,
	"severity"	TEXT NOT NULL DEFAULT 'info',
	PRIMARY KEY("notification_ID" AUTOINCREMENT),
	FOREIGN KEY("command_ID") REFERENCES "Commands"("command_ID") ON DELETE SET NULL,
	FOREIGN KEY("detection_ID") REFERENCES "Detection"("detection_ID") ON DELETE SET NULL,
	FOREIGN KEY("room_ID") REFERENCES "Room"("room_ID") ON DELETE CASCADE,
	FOREIGN KEY("user_ID") REFERENCES "Users"("users_ID") ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS "Room" (
	"room_ID"	INTEGER,
	"building_ID"	INTEGER NOT NULL,
	"room_name"	TEXT NOT NULL,
	"floor_plan_data"	TEXT,
	"plan_width"	REAL,
	"plan_height"	REAL,
	PRIMARY KEY("room_ID" AUTOINCREMENT),
	FOREIGN KEY("building_ID") REFERENCES "Building"("building_ID") ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS "Sensor_Readings" (
	"readings_ID"	INTEGER,
	"sensor_ID"	INTEGER NOT NULL,
	"temperature"	REAL,
	"humidity"	REAL,
	"occupied"	INTEGER,
	"recorded_at"	TEXT NOT NULL DEFAULT (datetime('now')),
	PRIMARY KEY("readings_ID" AUTOINCREMENT),
	FOREIGN KEY("sensor_ID") REFERENCES "Sensors"("sensor_ID") ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS "Sensors" (
	"sensor_ID"	INTEGER,
	"controller_ID"	INTEGER NOT NULL,
	"sensor_type"	TEXT NOT NULL,
	"gpio_pin"	INTEGER,
	"pos_x"	REAL,
	"pos_y"	REAL,
	PRIMARY KEY("sensor_ID" AUTOINCREMENT),
	FOREIGN KEY("controller_ID") REFERENCES "Controllers"("controllers_ID") ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS "User_Room_Access" (
	"users_ID"	INTEGER NOT NULL,
	"room_ID"	INTEGER NOT NULL,
	PRIMARY KEY("users_ID","room_ID"),
	FOREIGN KEY("room_ID") REFERENCES "Room"("room_ID") ON DELETE CASCADE,
	FOREIGN KEY("users_ID") REFERENCES "Users"("users_ID") ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS "Users" (
	"users_ID"	INTEGER,
	"users_name"	TEXT NOT NULL,
	"users_email"	TEXT NOT NULL UNIQUE,
	"users_password_hash"	TEXT NOT NULL,
	"role"	TEXT NOT NULL DEFAULT 'user',
	"created_at"	TEXT DEFAULT (datetime('now')),
	PRIMARY KEY("users_ID" AUTOINCREMENT)
);
